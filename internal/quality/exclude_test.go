func TestDefaultExclusions(t *testing.T) {
	tests := []struct {
		path string
		want bool
	}{
		{"internal/ui/app.go", false},
		{"src/main.py", false},
		{"web/app.ts", false},
		{"lib/thing.ex", false},
		{"vendor/x/y.go", true},
		{"a/node_modules/pkg/index.js", true},
		{"third_party/lib/a.c", true},
		{"pkg/testdata/in.go", true},
		{"app_test.go", true},
		{"pkg/test_models.py", true},
		{"pkg/models_test.py", true},
		{"web/app.test.ts", true},
		{"web/app.spec.ts", true},
		{"web/app.test.js", true},
		{"tests/helper.py", true},
		{"test/helper.rb", true},
		{"spec/helper.rb", true},
		{"src/latest.py", false},
		{"src/contest/a.py", false},
	}
	for _, tt := range tests {
		t.Run(tt.path, func(t *testing.T) {
			assert.Equal(t, Excluder{}.Path(tt.path), tt.want)
		})
	}
}

func TestExcluderOverrides(t *testing.T) {
	tests := []struct {
		name string
		cfg  ExcludeConfig
		path string
		want bool
	}{
		{"user glob with **", ExcludeConfig{Exclude: []string{"internal/db/sqlcdb/**"}}, "internal/db/sqlcdb/a/q.go", true},
		{"user glob leaves others", ExcludeConfig{Exclude: []string{"internal/db/sqlcdb/**"}}, "internal/db/x.go", false},
		{"star stays in a directory", ExcludeConfig{Exclude: []string{"src/*.py"}}, "src/a/b.py", false},
		{"star matches a name", ExcludeConfig{Exclude: []string{"src/*.py"}}, "src/b.py", true},
		{"leading **/", ExcludeConfig{Exclude: []string{"**/gen_*.go"}}, "a/b/gen_x.go", true},
		{"leading **/ at the root", ExcludeConfig{Exclude: []string{"**/gen_*.go"}}, "gen_x.go", true},
		{"directory glob", ExcludeConfig{Exclude: []string{"docs/"}}, "docs/a/b.py", true},
		{"include rescues a default", ExcludeConfig{Include: []string{"vendor/mine/**"}}, "vendor/mine/a.go", false},
		{"include keeps the rest excluded", ExcludeConfig{Include: []string{"vendor/mine/**"}}, "vendor/theirs/a.go", true},
		{"defaults off", ExcludeConfig{NoDefaults: true}, "vendor/x/a.go", false},
		{"defaults off, user glob on", ExcludeConfig{NoDefaults: true, Exclude: []string{"gen/**"}}, "gen/a.go", true},
		{"exclude wins over include", ExcludeConfig{Include: []string{"a/**"}, Exclude: []string{"a/b/**"}}, "a/b/c.go", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ex, err := NewExcluder(tt.cfg)
			assert.NilError(t, err)
			assert.Equal(t, ex.Path(tt.path), tt.want)
		})
	}
}

func TestExcluderRejectsAnEmptyGlob(t *testing.T) {
	_, err := NewExcluder(ExcludeConfig{Exclude: []string{" "}})
	assert.ErrorContains(t, err, "empty glob")
	assert.NilError(t, ValidateGlob("a/**/b?.go"))
}

func TestShellPatternsOnlyWhenTheDefaultsAreFinal(t *testing.T) {
	assert.Assert(t, len(Excluder{}.ShellPatterns()) > 0)
	off, _ := NewExcluder(ExcludeConfig{NoDefaults: true})
	assert.Equal(t, len(off.ShellPatterns()), 0)
	inc, _ := NewExcluder(ExcludeConfig{Include: []string{"vendor/x/**"}})
	assert.Equal(t, len(inc.ShellPatterns()), 0)
}

func TestGenerated(t *testing.T) {
	tests := []struct {
		src  string
		want bool
	}{
		{"// Code generated by protoc. DO NOT EDIT.\npackage p\n", true},
		{"# @generated\nx = 1\n", true},
		{"/* AUTOGENERATED */\n", true},
		{"package p\n\nfunc f() {}\n", false},
		{"\n\n\n\n\n\n\n\n\n\n\n// DO NOT EDIT\n", false},
	}
	for _, tt := range tests {
		assert.Equal(t, Generated([]byte(tt.src)), tt.want, tt.src)
	}
}
